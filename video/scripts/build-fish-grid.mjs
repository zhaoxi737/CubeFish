// One-off generator: reads the launcher's pixel-fish SVG and emits the 18x13
// grid used by the Remotion project. The SVG itself is only read, never edited.
// Usage (from video/): node scripts/build-fish-grid.mjs
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const svgPath = path.resolve(here, '../../src/renderer/assets/logo-fish.svg');
const outPath = path.resolve(here, '../src/FishGrid.ts');

const svg = readFileSync(svgPath, 'utf8');
const rects = [...svg.matchAll(/<rect x="(\d+)" y="(\d+)" width="1" height="1" fill="#([0-9A-Fa-f]{6})"\/>/g)].map(
  (m) => ({x: Number(m[1]), y: Number(m[2]), hex: m[3].toUpperCase()}),
);

const width = 19;
const height = 14;
const raw = Array.from({length: height}, () => Array(width).fill('#000000'));

// The SVG paints some cells twice (outline first, highlight on top); later
// rects win, which matches SVG painter order.
for (const r of rects) {
  raw[r.y][r.x] = r.hex;
}

// Color -> cell type. The 4 semantic types requested by the brief. The SVG's
// #26561B outline / extrusion tone is folded into the "dark" type; the actual
// #26561B extrusion is rendered separately as each cube's bottom face.
const COLOR_TO_TYPE = {
  '5CB045': 1, // body
  '9CDD6E': 2, // highlight
  '3A7F2B': 3, // shadow
  '141F0D': 4, // eye
  '26561B': 3, // outline / thickness -> dark
};

// Bounding box of every painted cell in the 19x14 SVG viewBox.
let minX = width;
let maxX = -1;
let minY = height;
let maxY = -1;
for (let y = 0; y < height; y++) {
  for (let x = 0; x < width; x++) {
    if (raw[y][x] !== '#000000') {
      minX = Math.min(minX, x);
      maxX = Math.max(maxX, x);
      minY = Math.min(minY, y);
      maxY = Math.max(maxY, y);
    }
  }
}
const drawnW = maxX - minX + 1;
const drawnH = maxY - minY + 1;

const COLS = 18;
const ROWS = 13;
const OFF_X = Math.floor((COLS - drawnW) / 2); // center the 16px-wide fish
const OFF_Y = Math.ceil((ROWS - drawnH) / 2); // center the 12px-tall fish

const grid = Array.from({length: ROWS}, () => Array(COLS).fill(0));
for (let y = 0; y < drawnH; y++) {
  for (let x = 0; x < drawnW; x++) {
    const hex = raw[minY + y][minX + x];
    if (hex === '#000000') continue;
    const type = COLOR_TO_TYPE[hex];
    if (!type) throw new Error(`Unmapped color ${hex} at ${x},${y}`);
    grid[y + OFF_Y][x + OFF_X] = type;
  }
}

const rows = grid
  .map((row) => `  [${row.join(', ')}],`)
  .join('\n');

const file = `// AUTO-GENERATED by scripts/build-fish-grid.mjs from
// src/renderer/assets/logo-fish.svg (read-only source asset).
//
// 18 x 13 pixel grid. The fish drawing itself occupies a 16 x 12 area of the
// source SVG; it is centered inside this 18 x 13 canvas (1 empty column on each
// side, 1 empty row at the top).
//
// 0 = empty, 1 = body (#5CB045), 2 = highlight (#9CDD6E),
// 3 = shadow (#3A7F2B), 4 = eye (#141F0D)
export const FISH_GRID_COLS = ${COLS};
export const FISH_GRID_ROWS = ${ROWS};

export type FishCellType = 0 | 1 | 2 | 3 | 4;

export const FISH_GRID: readonly (readonly FishCellType[])[] = [
${rows}
];
`;

writeFileSync(outPath, file, 'utf8');
console.log(`wrote ${outPath} (${COLS}x${ROWS}, fish ${drawnW}x${drawnH}, origin ${OFF_X},${OFF_Y})`);
for (const row of grid) {
  console.log(row.map((v) => (v === 0 ? '.' : v === 1 ? '#' : v === 2 ? '+' : v === 3 ? 'x' : 'O')).join(''));
}
